"""Independent integer oracle, not an import of the TypeScript engine.

Transport computes each site's result from its four neighbors (Jacobi form),
unlike production's once-per-edge flux ledger. Fixtures are committed and never
regenerated by tests. Use --check to verify provenance; omit it to regenerate.
"""
import json
import sys
from pathlib import Path

MASK = 2**32 - 1


def draw(state):
    state = (state + 0x6D2B79F5) & MASK
    word = ((state ^ (state >> 15)) * (state | 1)) & MASK
    word ^= (word + (((word ^ (word >> 7)) * (word | 61)) & MASK)) & MASK
    return state, (word ^ (word >> 14)) & MASK


def reference_step(field, width, height, boundary, divisor):
    result = []
    for y in range(height):
        for x in range(width):
            value = field[y * width + x]
            change = 0
            for dx, dy in [(0, -1), (-1, 0), (0, 1), (1, 0)]:
                nx, ny = x + dx, y + dy
                if boundary == 'periodic':
                    nx, ny = nx % width, ny % height
                elif not (0 <= nx < width and 0 <= ny < height):
                    continue
                diff = field[ny * width + nx] - value
                change += (1 if diff >= 0 else -1) * (abs(diff) // divisor)
            result.append(value + change)
    return result


def generate():
    vectors = []
    for seed in [0, 1, MASK]:
        state, values = seed, []
        for _ in range(8):
            state, value = draw(state)
            values.append(value)
        vectors.append({'seed': seed, 'values': values, 'state': state})
    cases = []
    for seed, width, height, boundary, divisor, initializer in [
        (0, 8, 8, 'periodic', 8, 'uniform-noise'),
        (1, 8, 16, 'closed', 16, 'uniform-noise'),
        (MASK, 8, 8, 'periodic', 16, 'center-impulse'),
    ]:
        state, field = seed, [0] * (width * height)
        if initializer == 'uniform-noise':
            for i in range(len(field)):
                state, value = draw(state)
                field[i] = value >> 16
        else:
            field[(height // 2) * width + width // 2] = 65535
        frames = []
        for tick in range(101):
            if tick in [0, 1, 2, 10, 100]:
                frames.append({'tick': tick, 'field': field.copy(), 'sum': sum(field), 'min': min(field), 'max': max(field)})
            field = reference_step(field, width, height, boundary, divisor)
        cases.append({'seed': seed, 'width': width, 'height': height, 'boundary': boundary, 'divisor': divisor, 'initializer': initializer, 'rngState': state, 'frames': frames})
    return {'provenance': 'scripts/reference-fixtures.py: independent Python uint32 RNG and per-site neighbor solver; no production imports', 'vectors': vectors, 'cases': cases}


path = Path(__file__).resolve().parents[1] / 'tests/fixtures/substrate/reference.json'
result = json.dumps(generate(), indent=2) + '\n'
if '--check' in sys.argv:
    assert path.read_text() == result, 'Committed fixtures differ from the independent reference.'
    print('Independent reference fixtures verified.')
else:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(result)
