"""Independent Python life oracle. No TypeScript imports; uses Jacobi transport.
Committed fixtures are not regenerated by tests. --check verifies provenance.
"""
import importlib.util
import json
import sys
from copy import deepcopy
from pathlib import Path
spec = importlib.util.spec_from_file_location('substrate_oracle', Path(__file__).with_name('reference-fixtures.py'))
oracle = importlib.util.module_from_spec(spec)
spec.loader.exec_module(oracle)

def run(boundary):
    rng, field = 42, []
    for _ in range(64):
        rng, word = oracle.draw(rng)
        field.append(1024 + (word >> 22))
    field[36] -= 288
    organisms = [{'id': 1, 'cells': [36], 'energy': 256, 'score': 0, 'genome': {'maxCells': 4, 'bias': -2, 'resourceWeight': 1, 'energyWeight': 1}}]
    lineage = [{'id': 1, 'parent': None, 'born': 0, 'died': None, 'mutated': False}]
    dissipated, frames = 0, []
    def neighbors(site):
        x, y = site % 8, site // 8
        return [b % 8 * 8 + a % 8 for a, b in [(x,y-1),(x+1,y),(x,y+1),(x-1,y)] if boundary == 'periodic' or (0 <= a < 8 and 0 <= b < 8)]
    def candidate(o, occupied):
        sites = [p for c in o['cells'] for p in neighbors(c) if p not in occupied]
        return max(sites, key=lambda p: field[p]) if sites else None
    for tick in range(2001):
        if tick in [0, 1, 10, 100, 500, 2000]:
            frames.append(deepcopy({'tick': tick, 'rngState': rng, 'field': field, 'organisms': organisms, 'lineage': lineage, 'dissipated': dissipated}))
        if tick == 2000: break
        field = oracle.reference_step(field, 8, 8, boundary, 8)
        occupied = {p for o in organisms for p in o['cells']}
        output, newborns = [], 0
        for o in deepcopy(organisms):
            for p in o['cells']:
                intake = min(32, field[p], 8192-o['energy'])
                field[p] -= intake
                o['energy'] += intake
            cost = min(o['energy'], 2*len(o['cells']))
            o['energy'] -= cost
            dissipated += cost
            if o['energy'] == 0:
                release = 32*len(o['cells'])
                for p in o['cells']:
                    occupied.remove(p)
                    deposit = min(release, 65535-field[p])
                    field[p] += deposit
                    release -= deposit
                dissipated += release
                lineage[o['id']-1]['died'] = tick+1
                continue
            p, g = candidate(o, occupied), o['genome']
            o['score'] = g['bias'] + g['resourceWeight']*((0 if p is None else field[p])//256) + g['energyWeight']*(o['energy']//32)
            if p is not None and o['score'] >= 0 and o['energy'] >= 32 and len(o['cells']) < g['maxCells']:
                o['cells'].append(p)
                occupied.add(p)
                o['energy'] -= 32
            output.append(o)
            p = candidate(o, occupied)
            if p is not None and o['energy'] >= 512 and len(o['cells']) >= 2 and len(organisms)+newborns < 64 and len(lineage) < 512:
                o['energy'] -= 288
                genome, mutated = deepcopy(g), False
                rng, word = oracle.draw(rng)
                if word & 3 == 0:
                    rng, word = oracle.draw(rng)
                    key = ['maxCells','bias','resourceWeight','energyWeight'][word % 4]
                    before = genome[key]
                    genome[key] = max(2 if key == 'maxCells' else -8, min(8, before + (1 if word & 4 else -1)))
                    mutated = genome[key] != before
                child = len(lineage)+1
                output.append({'id': child, 'cells': [p], 'energy': 256, 'score': 0, 'genome': genome})
                lineage.append({'id': child, 'parent': o['id'], 'born': tick+1, 'died': None, 'mutated': mutated})
                occupied.add(p)
                newborns += 1
        organisms = sorted(output, key=lambda o:o['id'])
    return {'boundary': boundary, 'seed': 42, 'frames': frames}

if __name__ == '__main__':
    value = {'oracle': 'python-integer-life-v1', 'cases': [run('closed'),run('periodic')]}
    path = Path(__file__).resolve().parent.parent/'tests/fixtures/life-reference.json'
    text = json.dumps(value, indent=2)+'\n'
    if '--check' in sys.argv:
        assert path.read_text() == text, 'Life fixture provenance mismatch'
        print('Independent life fixtures verified')
    else:
        path.write_text(text)
